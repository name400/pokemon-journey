import assert from 'node:assert/strict';
import {client} from './release-client.mjs';
const a=client(1);await a.admin();
const worldRevision=(await a.call('/api/world')).revision;
let r=await a.call('/api/rogue');
if(r.data.run&&['battle','reward'].includes(r.data.screen))r=await a.call('/api/rogue',{action:'abandon',revision:r.revision});
const catalog=await a.call('/api/rogue?catalog=1');
assert.equal(catalog.balls.length,10);assert.ok(catalog.supplies.every(i=>i.image.endsWith('.png')));
assert.equal(catalog.capsules.find(c=>c.id==='all').count,1579);
const pack=catalog.capsules[0],beforeCoins=r.data.coins,beforeOwned=r.data.collectionCount;
await a.call('/api/rogue',{action:'gacha',pack:pack.id,expectedPrice:pack.price-250,pricingVersion:1,revision:r.revision},409);
assert.equal((await a.call('/api/rogue')).data.coins,beforeCoins);
r=await a.call('/api/rogue',{action:'gacha',pack:pack.id,expectedPrice:pack.price,pricingVersion:1,revision:r.revision});
assert.equal(r.data.coins,beforeCoins-pack.price);assert.equal(r.data.collectionCount,beforeOwned+1);
const drops=await a.call('/api/rogue?capsule=all');assert.equal(drops.pool.length,1579);
for(const ball of catalog.balls){const coins=r.data.coins,count=r.data.ballsAvailable.find(b=>b.id===ball.id).count;r=await a.call('/api/rogue',{action:'buyBall',ball:ball.id,quantity:2,revision:r.revision});assert.equal(r.data.coins,coins-2*ball.price);assert.equal(r.data.ballsAvailable.find(b=>b.id===ball.id).count,count+2);}
for(const qty of [0,-1,100,1.5])await a.call('/api/rogue',{action:'buyBall',ball:'masterball',quantity:qty,revision:r.revision},409);
const gift=await a.call('/api/admin',{action:'grantPokemon',mode:'rogue',target:'local_seedy',species:7,level:5,experience:0,moves:['몸통박치기','물대포']});
r=await a.call('/api/rogue');if(r.data.screen!=='choose')r=await a.call('/api/rogue',{action:'begin',revision:r.revision});
assert.equal(r.data.choices.length,3);
r=await a.call('/api/rogue',{action:'choose',boxId:gift.boxId,revision:r.revision});
const before=r.battle.teams[1][0].hp;
const move=r.battle.requests[0].moves.find(m=>m.name==='물대포');assert.equal(move.type,'물');assert.equal(move.power,40);assert.equal(move.category,'Special');
r=await a.call('/api/rogue',{action:'battle',command:{type:'move',move:move.name},revision:r.revision});
assert.ok(r.battle||r.finishedBattle);const v=r.battle||r.finishedBattle;
assert.ok(v.teams[1][0].hp<before,'a normal level-5 attack applies real HP damage');
assert.ok(v.before&&v.beforeActive,'animation receives authoritative before-state');
assert.ok(v.events.some(e=>e.kind==='move'));
assert.equal(v.teams[0][0].pp.watergun,move.pp-1);
if(r.data.screen==='reward')r=await a.call('/api/rogue',{action:'reward',kind:'heal',revision:r.revision});
const masterCount=r.data.ballsAvailable.find(b=>b.id==='masterball').count,collection=r.data.collectionCount;
r=await a.call('/api/rogue',{action:'ball',ball:'masterball',revision:r.revision});
assert.equal(r.data.screen,'reward');assert.equal(r.data.collectionCount,collection+1);
assert.equal(r.data.ballsAvailable.find(b=>b.id==='masterball').count,masterCount-1);
assert.equal(r.finishedBattle.ended,true);assert.equal(r.finishedBattle.winner,0);
assert.ok(r.finishedBattle.events.some(e=>e.kind==='capture'&&e.ball==='masterball'));
assert.equal((await a.call('/api/world')).revision,worldRevision);
console.log('Rogue catalog, ten ball purchases, exact coins/counts, level-5 attack/PP, before-state, real Master Ball capture and isolated world: passed');
